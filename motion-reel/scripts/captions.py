# Branch B subtitles: transcript/transcript.json → film/captions.js (window.CAPS: phrase chunks with word timings).
#   python3 scripts/captions.py
# Subtitles are ALWAYS on in Branch B. Optional inputs (project root):
#   captions.fix.json      {"proms": "prompts", "comentas": "comentá"}  spelling fixes, keyed by the lowercase spoken word
#   captions.phrases.txt   hand-cut chunks, "|"-separated, in spoken order (words after fixes). Without it, chunks are
#                          cut automatically: at pauses > 0.28 s, at phrase-start words, at most 4 words / 22 characters.
# The timing always stays the spoken one; only the spelling changes.
import json, os

TL = json.load(open('timeline.json', encoding='utf-8'))
DUR = float(TL['duration'])
FIX = json.load(open('captions.fix.json', encoding='utf-8')) if os.path.exists('captions.fix.json') else {}
words = [dict(w=FIX.get(x['word'].strip().lower(), x['word'].strip()), s=x['start'], e=x['end'])
         for seg in json.load(open('transcript/transcript.json', encoding='utf-8'))['segments'] for x in seg['words']]
if words: words[0]['w'] = words[0]['w'][:1].upper() + words[0]['w'][1:]

chunks = []
if os.path.exists('captions.phrases.txt'):
    i = 0
    for p in [p.split() for p in open('captions.phrases.txt', encoding='utf-8').read().replace('\n', ' ').split('|') if p.strip()]:
        c = words[i:i + len(p)]
        assert [x['w'] for x in c] == p, f'phrase mismatch: {p} vs {[x["w"] for x in c]}'
        chunks.append(c); i += len(p)
    assert i == len(words), f'{len(words) - i} words left over after captions.phrases.txt'
else:
    STARTS = {'pero', 'y', 'o', 'que', 'para', 'así', 'porque', 'and', 'but', 'or', 'so', 'because'}
    cur = []
    for i, w in enumerate(words):
        gap = w['s'] - words[i - 1]['e'] if i else 0
        text = ' '.join(x['w'] for x in cur + [w])
        if cur and (gap > 0.28 or len(cur) >= 4 or len(text) > 22 or (w['w'].lower() in STARTS and len(cur) >= 2)):
            chunks.append(cur); cur = []
        cur.append(w)
    if cur: chunks.append(cur)

out = []
for k, c in enumerate(chunks):
    nxt = chunks[k + 1][0]['s'] if k + 1 < len(chunks) else DUR
    out.append({'t0': round(c[0]['s'], 3), 't1': round(min(nxt, c[-1]['e'] + 0.6), 3), 'w': [[x['w'], round(x['s'], 3)] for x in c]})
open('film/captions.js', 'w', encoding='utf-8').write('// GENERATED by scripts/captions.py — do not edit\nwindow.CAPS = ' + json.dumps(out, ensure_ascii=False) + ';\n')
for c in out: print(f"{c['t0']:6.2f}-{c['t1']:6.2f}  {' '.join(w for w, _ in c['w'])}")
